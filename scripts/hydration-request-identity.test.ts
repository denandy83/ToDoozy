import { createRequire } from 'node:module'
import { afterEach, expect, it } from 'vitest'
const require=createRequire(import.meta.url)
const {makeHarness}=require('./benchmark-sync.cjs')
const opened:Awaited<ReturnType<typeof makeHarness>>[]=[]
afterEach(async()=>{for(const h of opened.splice(0))await h.stop()})
it.each(['foreign','current','same-user'])('binds the public hydration family to %s requested identity and access',async mode=>{
  const h=await makeHarness({ref:process.env.REVIEW_BASE_REF,projectCount:1,connected:false});opened.push(h)
  h.repo.tasks.create({id:'private-task',project_id:'p0',owner_id:'u',status_id:'s0',title:'RETAINED PRIVATE',is_in_my_day:1,due_date:'2020-01-01'})
  const label=h.repo.labels.create({id:'private-label',user_id:'u',project_id:'p0',name:'RETAINED LABEL'})
  h.repo.tasks.addLabel('private-task',label.id)
  h.repo.savedViews.create({id:'view-u',user_id:'u',name:'PRIVATE VIEW',filter_config:'{}'})
  if(mode==='foreign')h.setAccount('other')
  else if(mode==='same-user')h.stores.useAuthStore.setState({currentUser:{...h.stores.useAuthStore.getState().currentUser}})
  const task=h.stores.useTaskStore.getState(),labels=h.stores.useLabelStore.getState()
  await task.hydrateAllForUser('u')
  await task.hydrateMyDay('u')
  await task.hydrateAllForProject('p0')
  await task.hydrateTasks('p0')
  await task.hydrateArchived('p0')
  await task.hydrateAllTaskLabels('p0')
  await task.hydrateTaskLabels('private-task')
  await labels.hydrateLabels('p0')
  await h.stores.useStatusStore.getState().hydrateStatuses('p0')
  await h.stores.useSavedViewStore.getState().hydrate('u')
  await h.stores.useSavedViewStore.getState().hydrateCounts('u')
  h.stores.useSavedViewStore.getState().scheduleRecount('u');await h.runTimers()
  if(mode==='foreign'){
    expect(h.stores.useTaskStore.getState().tasks).toEqual({})
    expect(h.stores.useTaskStore.getState().taskLabels).toEqual({})
    expect(h.stores.useLabelStore.getState().labels).toEqual({})
    expect(h.stores.useStatusStore.getState().statuses).toEqual({})
    expect(h.stores.useSavedViewStore.getState().views).toEqual([])
    expect(h.stores.useSavedViewStore.getState().viewCounts).toEqual({})
  }else{
    expect(h.stores.useTaskStore.getState().tasks['private-task'].title).toBe('RETAINED PRIVATE')
    expect(h.stores.useTaskStore.getState().taskLabels['private-task'][0].name).toBe('RETAINED LABEL')
    expect(h.stores.useLabelStore.getState().labels['private-label'].name).toBe('RETAINED LABEL')
    expect(h.stores.useStatusStore.getState().statuses.s0).toBeDefined()
    expect(h.stores.useSavedViewStore.getState().views[0].id).toBe('view-u')
  }
  expect(h.repo.tasks.findById('private-task').title).toBe('RETAINED PRIVATE')
  expect(h.repo.labels.findById('private-label').name).toBe('RETAINED LABEL')
  expect(h.fixtureErrors).toEqual([])
})
it.each(['account','database'])('retains the actual App local-event listener origin after %s replacement',async change=>{
  const h=await makeHarness({ref:process.env.REVIEW_BASE_REF,projectCount:1,connected:false});opened.push(h)
  h.repo.tasks.create({id:'retained',project_id:'p0',owner_id:'u',status_id:'s0',title:'PRIVATE LISTENER'})
  h.stores.useProjectStore.setState({currentProjectId:'p0'})
  const cleanup=h.runLocalChanges()
  if(change==='account')h.setAccount('other');else h.replaceDatabase()
  const before=h.nativeCalls.length
  h.emitLocalChange();await h.untilIdle();await h.runTimers()
  expect(h.nativeCalls.slice(before).filter((call:{namespace:string;method:string})=>['tasks','statuses','labels','projects','savedViews'].includes(call.namespace))).toEqual([])
  expect(h.stores.useTaskStore.getState().tasks).toEqual({})
  expect(h.repo.tasks.findById('retained').title).toBe('PRIVATE LISTENER')
  cleanup?.();expect(h.fixtureErrors).toEqual([])
})
